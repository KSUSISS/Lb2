-- Школы: одна школа может иметь много школьников.
CREATE TABLE IF NOT EXISTS school (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

-- Адреса школьников.
CREATE TABLE IF NOT EXISTS addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    postal_code VARCHAR(255),
    country VARCHAR(255),
    region VARCHAR(255),
    district VARCHAR(255),
    city VARCHAR(255),
    street VARCHAR(255),
    house VARCHAR(255),
    apartment VARCHAR(255)
);

-- Школьники со ссылками на школу и адрес.
CREATE TABLE IF NOT EXISTS schoolchild (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name VARCHAR(255),
    first_name VARCHAR(255),
    middle_name VARCHAR(255),
    gender VARCHAR(255),
    nationality VARCHAR(255),
    height INTEGER NOT NULL,
    weight INTEGER NOT NULL,
    birth_date DATE,
    phone VARCHAR(255),
    school_class VARCHAR(255),
    school_id BIGINT NOT NULL,
    address_id BIGINT NOT NULL UNIQUE,
    CONSTRAINT fk_schoolchild_school
        FOREIGN KEY (school_id) REFERENCES school(id),
    CONSTRAINT fk_schoolchild_address
        FOREIGN KEY (address_id) REFERENCES addresses(id)
);
